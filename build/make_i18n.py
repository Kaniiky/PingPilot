def build():
    dicts = {"en": {}, "es": {}}
    for pt, en, es in T:
        dicts["en"][pt], dicts["es"][pt] = en, es
    for t in tweaks.CATALOG:
        en, es = TWEAKS[t["id"]]
        for lang, tr in (("en", en), ("es", es)):
            for pt, out in zip((t["title"], t["desc"], t["warn"]), tr):
                dicts[lang][pt] = out
    assert len(EXCLUDED) == len(tweaks.EXCLUDED), "EXCLUDED fora de sincronia com tweaks.py"
    for (title, _src, why), (en, es) in zip(tweaks.EXCLUDED, EXCLUDED):
        for lang, tr in (("en", en), ("es", es)):
            dicts[lang][title], dicts[lang][why] = tr
    for lang, d in dicts.items():
        path = os.path.join(ROOT, "ui", f"i18n-{lang}.js")
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"// Gerado por build/make_i18n.py — edite lá, não aqui.\nwindow.I18N_{lang.upper()} = ")
            json.dump(d, f, ensure_ascii=False, indent=1)
            f.write(";\n")
        print(f"{lang}: {len(d)} textos -> {path}")


if __name__ == "__main__":
    build()
